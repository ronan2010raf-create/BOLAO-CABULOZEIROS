create table if not exists public.players (
  id bigint generated by default as identity primary key,
  name text not null,
  points integer not null default 0 check (points >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.rounds (
  id bigint generated by default as identity primary key,
  round_number integer not null unique check (round_number > 0),
  round_date date,
  created_at timestamptz not null default now()
);

create table if not exists public.round_entries (
  id bigint generated by default as identity primary key,
  round_id bigint not null references public.rounds(id) on delete cascade,
  player_id bigint not null references public.players(id) on delete cascade,
  points integer not null check (points >= 0),
  unique (round_id, player_id)
);

alter table public.players enable row level security;
alter table public.rounds enable row level security;
alter table public.round_entries enable row level security;

drop policy if exists "Authenticated users can manage players" on public.players;
create policy "Authenticated users can manage players"
on public.players for all to authenticated
using (true) with check (true);

drop policy if exists "Authenticated users can manage rounds" on public.rounds;
create policy "Authenticated users can manage rounds"
on public.rounds for all to authenticated
using (true) with check (true);

drop policy if exists "Authenticated users can manage round entries" on public.round_entries;
create policy "Authenticated users can manage round entries"
on public.round_entries for all to authenticated
using (true) with check (true);

grant usage on schema public to authenticated;
grant select, insert, update, delete on public.players, public.rounds, public.round_entries to authenticated;
grant usage, select on all sequences in schema public to authenticated;
